package lecture6;

public class demo7 {
    public static void main(String[] args) {

        // RELATIONAL OPERATORS - (==,!=,<=,>=,<,>)

        int num1 = 5;
        int num2 = 10;
        int num3 = 5;

        // == 
        System.out.println(num1 == num2);
        System.out.println(num1 == num3);

        // !=
        System.out.println(num1 != num2);

        // <=
        System.out.println(num1 <= num2);

        // >=
        System.out.println(num2>=num3);

        // <
        System.out.println(num3<num2);

        // >
        System.out.println(num3>num1);
        
    }
    
}
