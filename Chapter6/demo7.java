package Chapter6;

public class demo7 {

    public static void main(String[] args) {
        // Relational operator ==,!=,<,>,<=,>=


        int num1 = 5;
        int num2 = 10;

        boolean c = (num1==num2);
        System.out.println(c);

        System.out.println(num1!=num2);
        System.out.println(num1<num2);
        System.out.println(num1>num2);
        System.out.println(num2<=num1);
        System.out.println(num1>=num2);
    }
    
}
