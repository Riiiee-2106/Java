package Chapter8;

public class demo15 {

    public static void main(String[] args) {
        // 1 to 10

       /*  
       for(initialization ; condition ; updation){
            do something
        }
            */


        for(int i=1;i<=10;i++){
            System.out.println(i);
        }

        /*
        flow of control of for -  
        1.first assignment statement is executed(variable definition.
        2.then second conditional statement is evaluated.(true/false).
        3.If true, control flow will evaluate the body of the loop.
        4.once loop body is finished,control flow will go back to the for of statement, and third increment statement will be evaluated.
        5.again, the conditional statement is evaluated.
        6.repeat 2-5.
        */


        for(int i=1;i<=10;i++){
            System.out.println(i);
        }


        //we also have for-each loop
        

    }
    
}
